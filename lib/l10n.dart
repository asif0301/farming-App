String translate(BuildContext context, String source) {
  if (Localizations.localeOf(context).languageCode != 'ur') return source;
  final exact = urduStrings[source];
  if (exact != null) return exact;
  // Translate display units without changing record IDs, names or numeric values.
  if (RegExp(r'^Rs -?[0-9.,]+$').hasMatch(source)) {
    return '${source.substring(3)} روپے';
  }
  if (RegExp(r'^-?[0-9.,]+ kg/day$').hasMatch(source)) {
    return source.replaceFirst(' kg/day', ' کلوگرام فی دن');
  }
  if (RegExp(r'^-?[0-9.,]+( → -?[0-9.,]+)? kg$').hasMatch(source)) {
    return source.replaceFirst(' kg', ' کلوگرام');
  }
  if (RegExp(r'^[0-9]+ head$').hasMatch(source)) {
    return source.replaceFirst(' head', ' جانور');
  }
  if (source.endsWith(' • Pakistan time')) {
    return source.replaceFirst('Pakistan time', 'پاکستانی وقت');
  }
  return source;
}

/// A const-friendly localized label. Locale dependencies update even const labels.
class AppText extends StatelessWidget {
  final String data;
  final TextStyle? style;
  final TextAlign? textAlign;
  final int? maxLines;
  final TextOverflow? overflow;
  const AppText(
    this.data, {
    super.key,
    this.style,
    this.textAlign,
    this.maxLines,
    this.overflow,
  });
  @override
  Widget build(BuildContext context) => Text(
    translate(context, data),
    style: style,
    textAlign: textAlign,
    maxLines: maxLines,
    overflow: overflow,
  );
}
